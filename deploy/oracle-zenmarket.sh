# Python + dépendances (attend la fin des mises à jour automatiques du 1er démarrage)
export DEBIAN_FRONTEND=noninteractive
apt-get -o DPkg::Lock::Timeout=900 update
apt-get -o DPkg::Lock::Timeout=900 install -y python3-venv curl
python3 -m venv .venv
.venv/bin/pip install -q -r requirements.txt

# Codes Discord (lisibles seulement par le bot)
printf 'DISCORD_BOT_TOKEN=%s\nDISCORD_CHANNEL_ID=%s\n' "$DISCORD_BOT_TOKEN" "$DISCORD_CHANNEL_ID" > .env
id zenbot >/dev/null 2>&1 || useradd --system --shell /usr/sbin/nologin zenbot
chown -R zenbot:zenbot "$DIR"
chmod 600 .env

# Service : démarre tout seul, redémarre après une panne ou un redémarrage du serveur
cat > /etc/systemd/system/zenmarket-bot.service <<'UNIT'
[Unit]
Description=Bot ZenMarket (surveillance 24/7, alertes Discord)
After=network-online.target
Wants=network-online.target

[Service]
User=zenbot
WorkingDirectory=/opt/zenmarket-bot
EnvironmentFile=/opt/zenmarket-bot/.env
ExecStart=/opt/zenmarket-bot/.venv/bin/python -m bot.main
Restart=always
RestartSec=30

[Install]
WantedBy=multi-user.target
UNIT
systemctl daemon-reload
systemctl enable --now zenmarket-bot
